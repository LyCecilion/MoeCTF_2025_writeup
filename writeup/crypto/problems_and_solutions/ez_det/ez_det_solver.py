# Gaussian elimination (exact with Fraction)
def gauss_jordan(mat):
    mat = [row[:] for row in mat]
    rows = len(mat)
    cols = len(mat[0]) - 1
    r = 0
    for c in range(cols):
        # find pivot
        piv = None
        for i in range(r, rows):
            if mat[i][c] != 0:
                piv = i
                break
        if piv is None:
            continue
        mat[r], mat[piv] = mat[piv], mat[r]
        pv = mat[r][c]
        # normalize pivot row
        for j in range(c, cols+1):
            mat[r][j] /= pv
        # eliminate other rows
        for i in range(rows):
            if i != r and mat[i][c] != 0:
                fac = mat[i][c]
                for j in range(c, cols+1):
                    mat[i][j] -= fac * mat[r][j]
        r += 1
        if r == rows:
            break
    # read solution (assumes unique solution)
    sol = [Fraction(0)]*cols
    for i in range(rows):
        # find leading column
        lead = None
        for j in range(cols):
            if mat[i][j] != 0:
                lead = j
                break
        if lead is not None:
            sol[lead] = mat[i][-1]
    return sol

